def test_dftd_plugin(
    constants: ConstantsForceAndStress,
    additions: AdditionsForceAndStress,
    config_version: str,
    config_method: str,
    reference: AdditionsForceAndStress,
) -> None:
    import os

    with NamedTemporaryFile("w", suffix=".toml") as fd:
        fd.write(f'version = "{config_version}"\n')
        fd.write(f'method = "{config_method}"\n')
        fd.flush()

        os.environ["DFTD_VASP_PLUGIN_INPUT"] = str(Path(fd.name).with_suffix(""))
        main(constants, additions)

    assert np.allclose(
        additions.total_energy, reference.total_energy
    ), "Total energy was not modified correctly"
    assert np.allclose(
        additions.forces, reference.forces
    ), "Forces were not modified correctly"
    assert np.allclose(
        additions.stress, reference.stress
    ), "Stress was not modified correctly"
